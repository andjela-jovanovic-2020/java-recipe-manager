    private void stilizujDugme(JButton dugme, Color osnovna, Color hover) {
    dugme.setContentAreaFilled(false);
    dugme.setOpaque(true);
    dugme.setBorderPainted(false);
    dugme.setFocusPainted(false);
    dugme.setBackground(osnovna);

    dugme.addMouseListener(new java.awt.event.MouseAdapter() {
        @Override
        public void mouseEntered(java.awt.event.MouseEvent evt) {
            dugme.setBackground(hover);
        }

        @Override
        public void mouseExited(java.awt.event.MouseEvent evt) {
            dugme.setBackground(osnovna);
        }
    });
}
    


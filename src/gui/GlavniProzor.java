    private void izborKategorijaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_izborKategorijaActionPerformed
        // TODO add your handling code here:
        if(!ucitano){
            return;
        }
        promeniPodnaslov(izborKategorija.getSelectedItem().toString(), new Color(112,142,108));
        ObradaRecepta or = new ObradaRecepta();
        Kategorija kat = (Kategorija) izborKategorija.getSelectedItem();
        ArrayList<Recept> lista = or.vratiReceptePoKategoriji(kat);
        srediDesniPanel(lista, new Color(158,172,156));
        
    }//GEN-LAST:event_izborKategorijaActionPerformed
    
    private void postaviKategorije(){
        ObradaKategorije ok = new ObradaKategorije();
        ArrayList<Kategorija> lista = ok.prikaziKategorije();
        for(Kategorija kat:lista){
            izborKategorija.addItem(kat);
            
        }
        
    }
    
    
    public void promeniPodnaslov(String podnaslov, Color color){
        labelPodnaslov.setText(podnaslov);
        labelPodnaslov.setForeground(color);
    }
    
    
    private void slicicaPanelLevo(){
        labelSlikaL.setVerticalAlignment(CENTER);
        labelSlikaL.setHorizontalAlignment(CENTER);
        ImageIcon ii = new ImageIcon("slike/ss.png");
        Image slika = ii.getImage();
        Image srSlika = slika.getScaledInstance(270, 220, Image.SCALE_SMOOTH);
        labelSlikaL.setIcon(new ImageIcon(srSlika));
    }
    
    
    
    
    
    

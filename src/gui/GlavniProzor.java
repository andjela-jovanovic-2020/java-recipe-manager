    //menja liste u zavisnosti od filtera
    private void srediDesniPanel(ArrayList<Recept> lista, Color color){
        unutrasnjiPanel.removeAll();
        if(lista.isEmpty()){
            PorukaPretrage pp = new PorukaPretrage();
            unutrasnjiPanel.add(pp);
            unutrasnjiPanel.revalidate();
            unutrasnjiPanel.repaint();
            return;
            
        }
        for(Recept recept : lista){
            KarticaRecepta kr = new KarticaRecepta(recept, color,this);
            unutrasnjiPanel.add(kr);
            unutrasnjiPanel.add(Box.createVerticalStrut(10));
            
        } 
        
        unutrasnjiPanel.revalidate();
        unutrasnjiPanel.repaint();
    }
    

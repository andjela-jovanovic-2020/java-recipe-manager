    private void dugmeDodajSastojakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dugmeDodajSastojakActionPerformed
        // TODO add your handling code here:
            if(!proveraUnosaSastojka()){
                return;
            }
            ReceptSastojak rs = new ReceptSastojak();
        
            Sastojak sas = new Sastojak();
            sas.setSastojak(nazivSastojak.getText());

            rs.setSastojak(sas);
            rs.setKolicina(Integer.parseInt(kolicinaSastojak.getText()));
            rs.setJedinica(jedinicaSastojak.getSelectedItem().toString());

            listaSastojak.add(rs);
            
            osveziPrikazSastojaka();
            
         
    }//GEN-LAST:event_dugmeDodajSastojakActionPerformed


    private void dugmeSacuvajReceptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dugmeSacuvajReceptActionPerformed
        // TODO add your handling code here:
        if(!proveraUnosaRecepta()){
            return;
        }
        if(!proveraListeSastojaka()){
            return;
        }
        Recept recept = new Recept();
        ObradaRecepta or = new ObradaRecepta();
        ObradaSastojka os = new ObradaSastojka();
        
        Kategorija kat = (Kategorija) boxKategorija.getSelectedItem();
        recept.setNaziv(poljeNaziv.getText().trim());
        recept.setVremePripreme(Integer.parseInt(poljeVreme.getText().trim()));
        recept.setKategorija(kat);
        recept.setOpis(poljeOpis.getText());
        or.dodajRecept(recept);
        ObradaSlike obrs = new ObradaSlike();
        
        if(fajl != null && obrs.proveraFajla(fajl)){
            nazivSlike = obrs.kreirajNazivSlike(fajl, recept.getId());
            obrs.kopirajSliku(fajl, nazivSlike);
            or.azurirajSliku(recept, nazivSlike);
        }
        
        for(ReceptSastojak rs :listaSastojak){
            rs.setRecept(recept);
            os.dodajSastojak(rs);
        }
        
        JOptionPane.showMessageDialog(this, "Uspesno dodat recept!");
        ocistiPolja();
    }//GEN-LAST:event_dugmeSacuvajReceptActionPerformed

    private boolean proveraUnosaRecepta(){
        String naziv = poljeNaziv.getText().trim();
        String opis = poljeOpis.getText().trim();
        String vreme = poljeVreme.getText().trim();
        if(naziv.isEmpty() || opis.isEmpty() || vreme.isEmpty()){
            JOptionPane.showMessageDialog(this, "Popunite sva polja.");
            return false;
        }
        try{
            int br = Integer.parseInt(vreme);
            
            if(br <= 0){
                JOptionPane.showMessageDialog(this, "Vreme mora biti vece od 0.");
                return false;
            }
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Unos vremena mora biti broj.");
            return false;
        }
         
        return true;
    }
    
    private boolean proveraListeSastojaka(){
        if(listaSastojak.isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite sastojke.");
            return false;
        }
        return true;
    }
    

    private void izborSlike() {
        JFileChooser fc = new JFileChooser();
        int rezultat = fc.showOpenDialog(this);

        if (rezultat != JFileChooser.APPROVE_OPTION) {
            return;
        }

        fajl = fc.getSelectedFile();
        putanjaSlike.setText(fajl.getName());
    }
    
    private boolean proveraUnosaSastojka(){
        String naziv = nazivSastojak.getText().trim();
        String poljeVreme = kolicinaSastojak.getText().trim();
        
        if(naziv.isEmpty() || poljeVreme.isEmpty()){
            JOptionPane.showMessageDialog(this, "Popunite sva polja.");
            return false;
        }
        
        try{
            int br = Integer.valueOf(poljeVreme);
            if(br <= 0){
                JOptionPane.showMessageDialog(this, "Broj mora biti veci od 0.");
                return false;
            }
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Unos kolicine mora biti broj.");
            return false;
        }
        
        
        return true;
    }
    

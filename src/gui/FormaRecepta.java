    private void osveziPrikazSastojaka(){
        panelPriv.removeAll();
        
        for(ReceptSastojak rs : listaSastojak){
            Runnable akcija = () -> {
                listaSastojak.remove(rs);
                osveziPrikazSastojaka();
            };
            KarticaSastojka ks = new KarticaSastojka(rs,
                    () -> { 
                        listaSastojak.remove(rs);
                         osveziPrikazSastojaka();
                    });
            
            
            panelPriv.add(ks);
            panelPriv.add(Box.createVerticalStrut(1));
        
        }
        nazivSastojak.setText("");
        kolicinaSastojak.setText("");
        panelPriv.revalidate();
        panelPriv.repaint();
        
    }


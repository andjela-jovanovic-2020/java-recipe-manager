    private void prikaziSliku(){
        labelSlika.setVerticalAlignment(CENTER);
        labelSlika.setHorizontalAlignment(CENTER);
        String nazivSlike = recept.getSlika();
        ImageIcon ic;
        
        if(nazivSlike == null || nazivSlike.isEmpty()){
            ic = new ImageIcon("slike/zamena.jpg");
        }else{
            ic = new ImageIcon("slike/" + nazivSlike);
        }
        
        Image slika = ic.getImage();
        
        int slikaS = ic.getIconWidth();
        int slikaV = ic.getIconHeight();
        
        int maxS = 540;
        int maxV = 240;
        
        double x = (double) maxS / slikaS;
        double y = (double) maxV / slikaV;
        double v = Math.min(x, y);
        
        int novaS = (int) (slikaS * v);
        int novaV = (int) (slikaV * v);
        
        Image sredjenaSlika = slika.getScaledInstance(novaS, novaV, Image.SCALE_SMOOTH);
        labelSlika.setIcon(new ImageIcon(sredjenaSlika));
    }
    
    
    
    

    private void ubaciSastojke(ObradaSastojka os, Recept recept){
        panelSastojaka.removeAll();
        
        ArrayList<ReceptSastojak> lista = os.vratiSastojke(recept);
        for(ReceptSastojak sastojak : lista){
            KarticaDetSastojaka kds = new KarticaDetSastojaka(sastojak);
            
            panelSastojaka.add(kds);
            panelSastojaka.add(Box.createVerticalStrut(3));
            
        }
        
        panelSastojaka.revalidate();
        panelSastojaka.repaint();
    }
    
    


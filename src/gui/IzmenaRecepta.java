    private void dugmeAzurirajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dugmeAzurirajActionPerformed
        // TODO add your handling code here:
        if(!proveraUnosaRecepta()){
            return;
        }
        if(!proveraListeSastojaka()){
            return;
        }
        ObradaRecepta or = new ObradaRecepta();
        ObradaSastojka os = new ObradaSastojka();
        Kategorija kat = (Kategorija) boxKategorija.getSelectedItem();
        recept.setNaziv(poljeNazivIzmena.getText().trim());
        recept.setVremePripreme(Integer.parseInt(poljeVremeIzmena.getText().trim()));
        recept.setKategorija(kat);
        recept.setOpis(poljeOpisIzmena.getText());
        recept.setId(recept.getId());
        
        or.izmeniRecept(recept);
        os.obrisiSveSastojke(recept);
        for(ReceptSastojak rs :listaSastojak){
            rs.setRecept(recept);
            os.dodajSastojak(rs);
        }
        
        JOptionPane.showMessageDialog(this, "Uspesno izmenjen recept!");
        //ocistiPolja();
        glavniProzor.postaviOmiljeniPanel();
    }//GEN-LAST:event_dugmeAzurirajActionPerformed

    private boolean proveraUnosaRecepta(){
        String naziv = poljeNazivIzmena.getText().trim();
        String opis = poljeOpisIzmena.getText().trim();
        String vreme = poljeVremeIzmena.getText().trim();
        if(naziv.isEmpty() || opis.isEmpty() || vreme.isEmpty()){
            JOptionPane.showMessageDialog(this, "Popunite sva polja.");
            return false;
        }
        try{
            int br = Integer.parseInt(vreme);
            
            if(br <= 0){
                JOptionPane.showMessageDialog(this, "Vreme mora biti vece od 0.");
                return false;
            }
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Unos vremena mora biti broj.");
            return false;
        }
         
        return true;
    }
    
    private boolean proveraListeSastojaka(){
        if(listaSastojak.isEmpty()){
            JOptionPane.showMessageDialog(this, "Unesite sastojke.");
            return false;
        }
        return true;
    }
    
